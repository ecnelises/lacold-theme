    class Emacs < Base
      def id = "emacs"
      def name = "Emacs"
      def description = "Emacs custom themes"

      def render(themes)
        files = themes.map { |theme| output("emacs/#{theme.id}-theme.el", emacs_theme(theme)) }
        files << output("emacs/README.md", <<~MARKDOWN)
          # Lacold for Emacs

          Copy theme files into a directory in `custom-theme-load-path`, then
          run `(load-theme 'lacold-air-blue-dark t)`. Themes cover core Emacs,
          Font Lock, search, completion, Diff, VC, compilation, Flymake, Dired,
          shells, Org, Magit, Corfu, Company, and Vertico faces.
        MARKDOWN
      end

      private

      def emacs_theme(theme)
        faces = core_faces(theme)
          .merge(font_lock_faces(theme))
          .merge(completion_faces(theme))
          .merge(tool_faces(theme))
          .merge(org_faces(theme))
          .merge(package_faces(theme))

        theme.ansi.each do |name, color|
          faces[:"ansi_color_#{name}"] = face(theme, color)
        end
        declarations = faces.map { |face, spec| "   '(#{face.to_s.tr("_", "-")} #{spec})" }.join("\n")
        <<~ELISP
          ;;; #{theme.id}-theme.el --- #{theme.name} -*- lexical-binding: t; -*-
          ;; Generated by Lacold #{Lacold::VERSION}. Do not edit generated releases.
          (deftheme #{theme.id} "#{theme.name}"
            :family 'lacold :kind 'color-scheme :background-mode '#{theme.mode})
          (custom-theme-set-faces
           '#{theme.id}
          #{declarations})
          (provide-theme '#{theme.id})
          ;;; #{theme.id}-theme.el ends here
        ELISP
      end

