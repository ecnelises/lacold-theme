      def diagnostic_face(theme, color, wash = :wash)
        face(theme, color, background: wash, underline: {color: theme.public_send(color), style: :wave})
      end

      def face(theme, foreground = nil, background: nil, **attributes)
        properties = {}
        properties[:foreground] = resolve_color(theme, foreground) if foreground
        properties[:background] = resolve_color(theme, background) if background
        properties.merge!(attributes)
        "((t (#{properties.map { |key, value| ":#{key.to_s.tr('_', '-')} #{elisp(value)}" }.join(' ')})))"
      end

      def resolve_color(theme, value)
        value.is_a?(Symbol) ? theme.public_send(value) : value
      end

      def elisp(value)
        case value
        when String then value.inspect
        when Symbol then value.to_s.tr("_", "-")
        when Hash
          "(#{value.map { |key, item| ":#{key.to_s.tr('_', '-')} #{elisp(item)}" }.join(' ')})"
        when TrueClass then "t"
        when FalseClass, NilClass then "nil"
        else value.to_s
        end
      end
    end
